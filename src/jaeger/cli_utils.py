def _deprecated_alias(command: click.Command, old_name: str) -> None:
    """Register *command* under *old_name* as a hidden, deprecated alias.

    The alias reuses the command's options and callback but emits a
    deprecation warning and is hidden from ``--help``.
    """
    alias = copy.copy(command)
    alias.name = old_name
    alias.hidden = True
    new_name = command.name
    alias.help = f"Deprecated alias for `{new_name}`."
    alias.short_help = f"Deprecated alias for `{new_name}`."
    original_callback = command.callback

    def callback(*args, **kwargs):
        logger.warning(
            f"'jaeger utils {old_name}' is deprecated; "
            f"use 'jaeger utils {new_name}' instead."
        )
        return original_callback(*args, **kwargs)

    alias.callback = callback
    utils.add_command(alias, old_name)


