@click.option(
    "--seq-col",
    "--seq_col",
    "seq_col",
    type=int,
    required=False,
    help="csv col with sequence",
)
@click.option(
    "--outtype",
    type=click.Choice(["CSV", "FASTA"], case_sensitive=False),
    required=False,
    help="output type",
    default="CSV",
)
@click.option(
    "--method",
    type=click.Choice(["ANI", "AAI"], case_sensitive=False),
    required=False,
    help="dereplication method",
    default="ANI",
)
@click.option(
    "--seed",
    type=int,
    required=False,
    default=None,
    help="Random seed for reproducible train/val/test splitting",
)
def dataset(**kwargs):
    """Generate a non-redundant fragment database from fasta file for training/validating
    fragment models"""
    from jaeger.commands.utils import dataset_core

    intype = kwargs.get("intype", "").upper()

    match intype:
        case "CSV":
            if not (
                kwargs.get("class_col") is not None
                and kwargs.get("seq_col") is not None
            ):
                raise click.UsageError(
                    "For CSV input, you must specify both --seq-col and --class-col."
                )
        case "FASTA":
            if kwargs.get("class_id") is None:
                raise click.UsageError("For FASTA input, you must specify --class.")
        case _:
            raise click.UsageError("Invalid input type: must be 'CSV' or 'FASTA'.")

    # build_dataset reads the ``class`` kwarg; map the click-safe ``class_id``.
    kwargs["class"] = kwargs.pop("class_id", None)
    dataset_core(**kwargs)


